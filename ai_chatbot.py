from openai import OpenAI

# Create the API client.
client = OpenAI()

# Store the conversation.
conversation = []


def chatbot():
    #Displays welcome message
    print("=" * 40)
    print("Welcome to PythonAI!")
    print("Type 'exit' to end the conversation.")
    print("=" * 40)

    while True:
        user_input = input("\nYou: ").strip()

        # Stop the chatbot if requested.
        if user_input.lower() == "exit":
            print("Bot: Goodbye! Thanks for chatting!")
            break

        # Ignore empty messages.
        if not user_input:
            continue

        # Add the user's message to the conversation.
        conversation.append({
            "role": "user",
            "content": user_input
        })

        try:
            # Send the conversation to the AI model.
            response = client.responses.create(
                model="gpt-4.1-mini",
                input=conversation
            )

            # Extract the generated answer.
            bot_reply = response.output_text

            #If there was an error in the response, raise an exception.
            if not bot_reply:
                raise ValueError("No response generated by the model.")
            elif "Something went wrong: Error code:" in bot_reply:
                raise ValueError(f"Error from model: {response.error}")

            print(f"\nBot: {bot_reply}")

            # Store the assistant's response.
            conversation.append({
                "role": "assistant",
                "content": bot_reply
            })

        except Exception as error:
            print(f"\nBot: Something went wrong: {error}")


if __name__ == "__main__":
    chatbot()